_nat_matrix_literal(M::AbstractMatrix) =
    "[" * join(["[" * join(M[i, :], ", ") * "]" for i in 1:size(M, 1)], ", ") * "]"

"""
    render_backprop_certificate(f::Cat.LinMap, g::Cat.LinMap; module_name=nothing) -> String

Emit a Lean certificate that **backprop is functorial** for the composite of two
layers `f`, `g` over ℤ_n: `(g∘f)ᵀ = fᵀ∘gᵀ` (the chain rule), proved by
`native_decide`. This is the categorical-deep-learning law made machine-checked.
"""
function render_backprop_certificate(f::Cat.LinMap, g::Cat.LinMap; module_name::Union{Nothing, String}=nothing)
    f.modulus == g.modulus || throw(ArgumentError("layers must share a modulus"))
    f.outdim == g.indim || throw(ArgumentError("layers not composable"))
    mod = module_name === nothing ? "BackpropCert" : module_name
    lines = String[]
    push!(lines, "-- Auto-generated by FunctorFlow.jl (backprop-as-functor certificate)")
    push!(lines, "namespace FunctorFlowProofs.Generated.$mod")
    push!(lines, "open FunctorFlowProofs")
    push!(lines, "")
    push!(lines, "def Fmat : List (List Nat) := $(_nat_matrix_literal(f.matrix))")
    push!(lines, "def Gmat : List (List Nat) := $(_nat_matrix_literal(g.matrix))")
    push!(lines, "")
    push!(lines, "-- (g ∘ f)ᵀ = fᵀ ∘ gᵀ  : backpropagation reverses the network (the chain rule)")
    push!(lines, "theorem backprop_chain_rule : chainRuleHolds $(f.modulus) Fmat Gmat = true := by native_decide")
    push!(lines, "")
    push!(lines, "end FunctorFlowProofs.Generated.$mod")
    join(lines, "\n")
end

