# Emit a MooreDecl literal for a Cat.MooreMachine.
function _moore_literal(M::Cat.MooreMachine)
    es(x) = lean_string(string(x))
    st = lean_list([es(s) for s in M.states])
    ins = lean_list([es(i) for i in M.inputs])
    trans = lean_list([
        "(($(es(s)), $(es(i))), $(es(M.transition[(s, i)])))" for s in M.states for i in M.inputs])
    out = lean_list(["($(es(s)), $(es(M.output[s])))" for s in M.states])
    "{ states := $st, inputs := $ins, transition := $trans, output := $out }"
end

