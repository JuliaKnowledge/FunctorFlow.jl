# ============================================================================
# cat_certificates.jl — emit Lean certificates for the Cat kernel
#
# Turns a finite `Cat.FreeCat` / `Cat.FinPresentedCat` into a `CatTable` and a
# `Cat.FinFunctor` into a `FunctorDecl` (see proofs/FunctorFlowProofs/Cat.lean),
# with a `native_decide` proof that the category / functor laws hold — a
# machine-checked counterpart to the kernel's runtime enumeration checks.
# Reuses `lean_string` / `lean_list` from `proof_interface.jl`.
# ============================================================================

# All morphisms (class representatives) of a finite category, deduplicated.
function _cat_morphisms(C)
    objs = Cat.objects(C)
    mors = Cat.PathMor[]
    seen = Set{Cat.PathMor}()
    for a in objs, b in objs, m in Cat.homset(C, a, b)
        m in seen || (push!(mors, m); push!(seen, m))
    end
    mors
end

# Emit the `CatTable` record literal for a finite category + the name map.
function _cat_table_literal(C)
    objs = Cat.objects(C)
    mors = _cat_morphisms(C)
    name = Dict{Cat.PathMor, String}()
    for (i, m) in enumerate(mors)
        name[m] = "m$(i - 1)"
    end
    obj_lit = lean_list([lean_string(string(o)) for o in objs])
    mor_lit = lean_list([
        "{ name := $(lean_string(name[m])), dom := $(lean_string(string(m.dom))), cod := $(lean_string(string(m.cod))) }"
        for m in mors])
    comp_entries = String[]
    for f in mors, g in mors
        f.cod == g.dom || continue
        h = Cat.compose(C, f, g)
        push!(comp_entries,
            "($(lean_string(name[f])), $(lean_string(name[g])), $(lean_string(name[h])))")
    end
    comp_lit = lean_list(comp_entries)
    id_lit = lean_list([
        "($(lean_string(string(o))), $(lean_string(name[Cat.id(C, o)])))" for o in objs])
    table = "{ objects := $obj_lit, morphisms := $mor_lit, comp := $comp_lit, ids := $id_lit }"
    (table, name)
end

"""
    render_cat_certificate(C; module_name=nothing) -> String

Emit a Lean certificate that a finite category `C` (`Cat.FreeCat` or
`Cat.FinPresentedCat`) satisfies the category axioms, proved by `native_decide`.
"""
function render_cat_certificate(C; module_name::Union{Nothing, String}=nothing)
    mod = module_name === nothing ? "CatCert" : module_name
    table, _ = _cat_table_literal(C)
    lines = String[]
    push!(lines, "-- Auto-generated by FunctorFlow.jl (Cat kernel certificate)")
    push!(lines, "namespace FunctorFlowProofs.Generated.$mod")
    push!(lines, "open FunctorFlowProofs")
    push!(lines, "")
    push!(lines, "def exportedCat : CatTable := $table")
    push!(lines, "")
    push!(lines, "theorem exportedCat_isCategory : exportedCat.isCategory = true := by native_decide")
    push!(lines, "")
    push!(lines, "end FunctorFlowProofs.Generated.$mod")
    join(lines, "\n")
end

"""
    render_functor_certificate(F::Cat.FinFunctor; module_name=nothing) -> String

Emit a Lean certificate that a finite functor `F` satisfies the functor laws
(and that its domain/codomain are categories), proved by `native_decide`.
"""
function render_functor_certificate(F::Cat.FinFunctor; module_name::Union{Nothing, String}=nothing)
    mod = module_name === nothing ? "FunctorCert" : module_name
    domtab, dname = _cat_table_literal(F.dom)
    codtab, cname = _cat_table_literal(F.cod)
    ob_lit = lean_list([
        "($(lean_string(string(o))), $(lean_string(string(F.ob_map[o]))))" for o in Cat.objects(F.dom)])
    mor_entries = String[]
    for p in _cat_morphisms(F.dom)
        Fp = F(p)
        push!(mor_entries, "($(lean_string(dname[p])), $(lean_string(cname[Fp])))")
    end
    mor_lit = lean_list(mor_entries)

    lines = String[]
    push!(lines, "-- Auto-generated by FunctorFlow.jl (Cat functor certificate)")
    push!(lines, "namespace FunctorFlowProofs.Generated.$mod")
    push!(lines, "open FunctorFlowProofs")
    push!(lines, "")
    push!(lines, "def domCat : CatTable := $domtab")
    push!(lines, "def codCat : CatTable := $codtab")
    push!(lines, "")
    push!(lines, "def exportedFunctor : FunctorDecl :=")
    push!(lines, "  { dom := domCat, cod := codCat, obMap := $ob_lit, morMap := $mor_lit }")
    push!(lines, "")
    push!(lines, "theorem domCat_isCategory : domCat.isCategory = true := by native_decide")
    push!(lines, "theorem codCat_isCategory : codCat.isCategory = true := by native_decide")
    push!(lines, "theorem exportedFunctor_isFunctor : exportedFunctor.isFunctor = true := by native_decide")
    push!(lines, "")
    push!(lines, "end FunctorFlowProofs.Generated.$mod")
    join(lines, "\n")
end

# obMap / morMap record fields for a functor, given its (co)domain name maps.
function _functor_maps(F, dname, cname)
    ob_lit = lean_list([
        "($(lean_string(string(o))), $(lean_string(string(F.ob_map[o]))))" for o in Cat.objects(F.dom)])
    mor_lit = lean_list([
        "($(lean_string(dname[p])), $(lean_string(cname[F(p)])))" for p in _cat_morphisms(F.dom)])
    (ob_lit, mor_lit)
end

# component list (object ↦ morphism name) for a nat-transformation over `cat`.
_component_list(comps, cat, namemap) = lean_list([
    "($(lean_string(string(o))), $(lean_string(namemap[comps[o]])))" for o in Cat.objects(cat)])

"""
    render_adjunction_certificate(adj::Cat.Adjunction; module_name=nothing) -> String

Emit a Lean certificate that `adj` is an adjunction (both functors are functors
and both triangle identities hold), proved by `native_decide`.
"""
function render_adjunction_certificate(adj::Cat.Adjunction; module_name::Union{Nothing, String}=nothing)
    mod = module_name === nothing ? "AdjCert" : module_name
    F, G = adj.left, adj.right
    Cobj, Dobj = F.dom, F.cod
    catC, nameC = _cat_table_literal(Cobj)
    catD, nameD = _cat_table_literal(Dobj)
    Fob, Fmor = _functor_maps(F, nameC, nameD)
    Gob, Gmor = _functor_maps(G, nameD, nameC)
    unit_lit = _component_list(adj.unit.components, Cobj, nameC)
    counit_lit = _component_list(adj.counit.components, Dobj, nameD)
    lines = String[]
    push!(lines, "-- Auto-generated by FunctorFlow.jl (Cat adjunction certificate)")
    push!(lines, "namespace FunctorFlowProofs.Generated.$mod")
    push!(lines, "open FunctorFlowProofs")
    push!(lines, "")
    push!(lines, "def catC : CatTable := $catC")
    push!(lines, "def catD : CatTable := $catD")
    push!(lines, "def leftFun : FunctorDecl := { dom := catC, cod := catD, obMap := $Fob, morMap := $Fmor }")
    push!(lines, "def rightFun : FunctorDecl := { dom := catD, cod := catC, obMap := $Gob, morMap := $Gmor }")
    push!(lines, "def exportedAdjunction : AdjunctionDecl :=")
    push!(lines, "  { F := leftFun, G := rightFun, unit := $unit_lit, counit := $counit_lit }")
    push!(lines, "")
    push!(lines, "theorem exportedAdjunction_isAdjunction : exportedAdjunction.isAdjunction = true := by native_decide")
    push!(lines, "")
    push!(lines, "end FunctorFlowProofs.Generated.$mod")
    join(lines, "\n")
end

# Emit a `SetDiagram` literal for a Set-valued functor X : C → FinSet.
function _set_diagram_literal(X::Cat.SetFunctor)
    C = X.cat
    es(x) = lean_string(string(x))
    objs_lit = lean_list([es(o) for o in Cat.objects(C)])
    sets_lit = lean_list([
        "($(es(o)), $(lean_list([es(e) for e in Cat.ob(X, o).elements])))" for o in Cat.objects(C)])
    edge_lits = String[]
    for (n, s, t) in C.edges
        f = X.edge_map[n]
        mp = lean_list(["($(es(x)), $(es(f(x))))" for x in Cat.ob(X, s).elements])
        push!(edge_lits, "{ src := $(es(s)), tgt := $(es(t)), map := $mp }")
    end
    "{ objs := $objs_lit, sets := $sets_lit, edges := $(lean_list(edge_lits)) }"
end

"""
    render_heyting_certificate(H::Cat.HeytingAlgebra; module_name=nothing) -> String

Emit a Lean certificate that `H` is a Heyting algebra (the adjunction
`z∧x ≤ y ⇔ z ≤ (x⇒y)`), proved by `native_decide`.
"""
function render_heyting_certificate(H::Cat.HeytingAlgebra; module_name::Union{Nothing, String}=nothing)
    mod = module_name === nothing ? "HeytingCert" : module_name
    es(x) = lean_string(string(x))
    elems = lean_list([es(x) for x in H.elements])
    leq = lean_list(["(($(es(x)), $(es(y))), $(Cat.hle(H, x, y)))" for x in H.elements for y in H.elements])
    meet = lean_list(["(($(es(x)), $(es(y))), $(es(Cat.hmeet(H, x, y))))" for x in H.elements for y in H.elements])
    imply = lean_list(["(($(es(x)), $(es(y))), $(es(Cat.himply(H, x, y))))" for x in H.elements for y in H.elements])
    lines = String[]
    push!(lines, "-- Auto-generated by FunctorFlow.jl (Heyting-algebra certificate)")
    push!(lines, "namespace FunctorFlowProofs.Generated.$mod")
    push!(lines, "open FunctorFlowProofs")
    push!(lines, "")
    push!(lines, "def exportedHeyting : HeytingDecl :=")
    push!(lines, "  { elements := $elems, leq := $leq, meet := $meet, imply := $imply }")
    push!(lines, "")
    push!(lines, "theorem exportedHeyting_isHeyting : exportedHeyting.isHeyting = true := by native_decide")
    push!(lines, "")
    push!(lines, "end FunctorFlowProofs.Generated.$mod")
    join(lines, "\n")
end

"""
    render_galois_certificate(P, Q, f, g; module_name=nothing) -> String

Emit a Lean certificate that `(f, g)` is a Galois connection between posets
`P`, `Q` (`f(p) ≤ q ⇔ p ≤ g(q)`), proved by `native_decide`.
"""
function render_galois_certificate(P::Cat.Poset, Q::Cat.Poset, f::AbstractDict, g::AbstractDict;
