    mod = module_name === nothing ? "GaloisCert" : module_name
    es(x) = lean_string(string(x))
    Pl = lean_list([es(x) for x in P.elements]); Ql = lean_list([es(x) for x in Q.elements])
    pleq = lean_list(["(($(es(x)), $(es(y))), $(Cat.ple(P, x, y)))" for x in P.elements for y in P.elements])
    qleq = lean_list(["(($(es(x)), $(es(y))), $(Cat.ple(Q, x, y)))" for x in Q.elements for y in Q.elements])
    fl = lean_list(["($(es(p)), $(es(f[p])))" for p in P.elements])
    gl = lean_list(["($(es(q)), $(es(g[q])))" for q in Q.elements])
    lines = String[]
    push!(lines, "-- Auto-generated by FunctorFlow.jl (Galois-connection certificate)")
    push!(lines, "namespace FunctorFlowProofs.Generated.$mod")
    push!(lines, "open FunctorFlowProofs")
    push!(lines, "")
    push!(lines, "def exportedGalois : GaloisDecl :=")
    push!(lines, "  { P := $Pl, Q := $Ql, pleq := $pleq, qleq := $qleq, f := $fl, g := $gl }")
    push!(lines, "")
    push!(lines, "theorem exportedGalois_isGalois : exportedGalois.isGalois = true := by native_decide")
    push!(lines, "")
    push!(lines, "end FunctorFlowProofs.Generated.$mod")
    join(lines, "\n")
end

